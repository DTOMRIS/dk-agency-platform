import assert from 'node:assert/strict';
import { bakuDay, customerWhatsappHref, followupFlag, initialFollowup, legacyStatus, salesInput, salesSummary } from '../lib/sales/followup';
const base = { ...initialFollowup({ id: '5c555555-5555-4555-8555-555555555555', status: 'new' }), ownerName: 'Doğan', nextAction: 'Call', nextContactOn: '2026-11-16' };
assert.ok(salesInput.safeParse(base).success);
assert.equal(salesInput.safeParse({ ...base, ownerName: '' }).success, false);
assert.equal(salesInput.safeParse({ ...base, nextContactOn: '2026-02-30' }).success, false);
assert.equal(salesInput.safeParse({ ...base, collectedAmount: -1 }).success, false);
assert.equal(salesInput.safeParse({ ...base, proposalAmount: 1.001 }).success, false);
assert.equal(salesInput.safeParse({ ...base, stage: 'lost', lossReason: '' }).success, false);
assert.ok(salesInput.safeParse({ ...base, stage: 'won', nextContactOn: null, ownerName: '', nextAction: '' }).success);
assert.equal(followupFlag(base, '2026-11-17'), 'overdue');
assert.equal(followupFlag({ ...base, stage: 'won' }, '2026-11-17'), 'closed');
assert.equal(followupFlag({ ...base, nextContactOn: null }, '2026-11-17'), 'unplanned');
assert.equal(bakuDay(new Date('2026-11-16T21:30:00Z')), '2026-11-17');
assert.equal(legacyStatus('proposal'), 'qualified');
assert.equal(initialFollowup({ id: base.leadId, status: 'converted' }).stage, 'won');
const stats = salesSummary([{ ...base, stage: 'proposal', proposalAmount: 500, collectedAmount: 100, spentMinutes: 60 }, { ...base, stage: 'won', proposalAmount: 900, collectedAmount: 700, spentMinutes: 30 }], '2026-11-17');
assert.deepEqual(stats, { total: 2, won: 1, overdue: 1, unplanned: 0, pipeline: 500, collected: 800, minutes: 90 });
assert.ok(customerWhatsappHref('050 123 45 67', 'Hello + & ?')?.startsWith('https://wa.me/994501234567?text=Hello%20%2B%20%26%20%3F'));
assert.equal(customerWhatsappHref('12', 'hello'), null);
console.info('Sales follow-up: validation, Baku days, actual collection vs open proposals, customer WhatsApp PASS');
